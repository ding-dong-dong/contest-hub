@app.get(
    "/contests/recommend",
    response_model=schemas.RecommendResponse,
    summary="???????",
    description=(
        "??????????????????????/??????????????У???????"
        "??????????????30 + ??????25 + ????????20 + ????????15 + ????????10??"
        "?????????????????ɡ?interests ????????Ρ?"
    ),
)
def get_recommend(
    grade: str = Query(..., description="???/???/????/????/?о???/????"),
    major: str = Query(..., description="?????/???????/????/???/??е/????/???/???/??/????"),
    interests: List[str] = Query(default_factory=list, description="?????????????????"),
    experience: str = Query(..., description="?????/?μ????δ??/?л????"),
    time_per_week: str = Query(..., description="??3С?/4-7С?/8-14С?/??15С?"),
    school: str = Query("", description="?У??????????"),
    db: Session = Depends(get_db),
):
    user = schemas.UserProfile(
        grade=grade,
        major=major,
        interests=interests,
        experience=experience,
        time_per_week=time_per_week,
        school=school,
    )
    contests = crud.list_contests(db)
    items = recommend.recommend(contests, user)
    return schemas.RecommendResponse(total=len(items), items=items)


